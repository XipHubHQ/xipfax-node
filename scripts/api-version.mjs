/**
 * Writes src/api-version.gen.ts from openapi.json: the version of XipFax's API the SDK is generated
 * from, which every request names in Xip-Version. `pnpm generate` runs it after the generator.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const document = JSON.parse(readFileSync(new URL('../openapi.json', import.meta.url), 'utf8'));
const version = document.info?.version;
if (typeof version !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(version)) {
  throw new Error(`openapi.json's info.version is ${JSON.stringify(version)}, not a day`);
}

writeFileSync(
  new URL('../src/api-version.gen.ts', import.meta.url),
  [
    "// Generated by scripts/api-version.mjs from openapi.json's info.version. Don't edit it.",
    '',
    '/** The version of XipFax’s API this SDK is generated from, which every request names. */',
    `export const API_VERSION = '${version}';`,
    '',
  ].join('\n'),
);
